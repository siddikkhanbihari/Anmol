class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('anmol_language') || 'gu'; // Default to Gujarati for Palanpur
    this.listeners = [];
  }

  getLang() {
    return this.currentLang;
  }

  t(key) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.en;
    return dict[key] || TRANSLATIONS.en[key] || key;
  }

  setLang(lang) {
    if (!TRANSLATIONS[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('anmol_language', lang);
    document.documentElement.lang = lang;
    this.translatePage();
    this.listeners.forEach(fn => fn(lang));
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }

  subscribe(callback) {
    this.listeners.push(callback);
    return () => {
      this.listeners = this.listeners.filter(cb => cb !== callback);
    };
  }

  translatePage() {
    // 1. Text elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation) {
        el.textContent = translation;
      }
    });

    // 2. HTML elements with data-i18n-html
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      const translation = this.t(key);
      if (translation) {
        el.innerHTML = translation;
      }
    });

    // 3. Inputs with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const translation = this.t(key);
      if (translation) {
        el.setAttribute('placeholder', translation);
      }
    });

    // 4. Update language switcher displays
    const currentLangObj = TRANSLATIONS[this.currentLang] || TRANSLATIONS.en;
    document.querySelectorAll('.current-lang-text').forEach(el => {
      el.textContent = currentLangObj.lang_name;
    });
    document.querySelectorAll('.current-lang-flag').forEach(el => {
      el.textContent = currentLangObj.flag;
    });

    // Highlight active option in switcher
    document.querySelectorAll('.lang-select-option').forEach(btn => {
      if (btn.dataset.lang === this.currentLang) {
        btn.classList.add('active');
        btn.style.fontWeight = '700';
        btn.style.color = 'var(--brand-blue)';
      } else {
        btn.classList.remove('active');
        btn.style.fontWeight = 'normal';
        btn.style.color = 'inherit';
      }
    });
  }

  // Render Language Switcher Widget
  renderSwitcher(containerSelector) {
    const containers = document.querySelectorAll(containerSelector);
    const curr = TRANSLATIONS[this.currentLang] || TRANSLATIONS.en;

    containers.forEach(container => {
      container.innerHTML = `
        <div class="language-dropdown-wrapper" style="position: relative; display: inline-block;">
          <button type="button" class="btn-lang-toggle" style="background: rgba(255,255,255,0.12); border: 1px solid rgba(255,255,255,0.25); border-radius: var(--radius-full); padding: 4px 10px; font-size: var(--font-size-xs); font-weight: 600; color: #FFF; display: flex; align-items: center; gap: 6px; cursor: pointer; transition: all 0.2s ease;">
            <span class="current-lang-flag">${curr.flag}</span>
            <span class="current-lang-text">${curr.lang_name}</span>
            <i class="fas fa-chevron-down" style="font-size: 0.6rem; opacity: 0.8;"></i>
          </button>
          
          <div class="lang-dropdown-panel" style="display: none; position: absolute; right: 0; top: calc(100% + 4px); background: #FFF; border: 1px solid var(--color-border); border-radius: var(--radius-md); box-shadow: var(--shadow-xl); z-index: 1000; min-width: 140px; overflow: hidden; padding: 4px 0;">
            <button type="button" class="lang-select-option ${this.currentLang === 'gu' ? 'active' : ''}" data-lang="gu" style="width: 100%; border: none; background: none; text-align: left; padding: 8px 12px; font-size: 0.82rem; cursor: pointer; display: flex; align-items: center; gap: 8px; font-weight: ${this.currentLang === 'gu' ? '700' : 'normal'}; color: ${this.currentLang === 'gu' ? 'var(--brand-blue)' : '#1E293B'};">
              <span>🇮🇳</span> <span>ગુજરાતી</span>
            </button>
            <button type="button" class="lang-select-option ${this.currentLang === 'hi' ? 'active' : ''}" data-lang="hi" style="width: 100%; border: none; background: none; text-align: left; padding: 8px 12px; font-size: 0.82rem; cursor: pointer; display: flex; align-items: center; gap: 8px; font-weight: ${this.currentLang === 'hi' ? '700' : 'normal'}; color: ${this.currentLang === 'hi' ? 'var(--brand-blue)' : '#1E293B'};">
              <span>🇮🇳</span> <span>हिन्दी</span>
            </button>
            <button type="button" class="lang-select-option ${this.currentLang === 'en' ? 'active' : ''}" data-lang="en" style="width: 100%; border: none; background: none; text-align: left; padding: 8px 12px; font-size: 0.82rem; cursor: pointer; display: flex; align-items: center; gap: 8px; font-weight: ${this.currentLang === 'en' ? '700' : 'normal'}; color: ${this.currentLang === 'en' ? 'var(--brand-blue)' : '#1E293B'};">
              <span>🇬🇧</span> <span>English</span>
            </button>
          </div>
        </div>
      `;

      const toggleBtn = container.querySelector('.btn-lang-toggle');
      const panel = container.querySelector('.lang-dropdown-panel');

      toggleBtn?.addEventListener('click', (e) => {
        e.stopPropagation();
        panel.style.display = panel.style.display === 'block' ? 'none' : 'block';
      });

      container.querySelectorAll('.lang-select-option').forEach(opt => {
        opt.addEventListener('click', (e) => {
          e.stopPropagation();
          const lang = opt.dataset.lang;
          this.setLang(lang);
          panel.style.display = 'none';
        });
      });
    });

    document.addEventListener('click', () => {
      document.querySelectorAll('.lang-dropdown-panel').forEach(p => p.style.display = 'none');
    });
  }
}

export const i18n = new I18nManager();
